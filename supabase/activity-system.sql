create or replace function public.get_user_activity_summary(p_user_id uuid)
returns table(score integer, title text)
language sql stable security definer set search_path = public as $$
  select coalesce(public.calculate_user_activity(p_user_id), 0),
    public.activity_title(coalesce(public.calculate_user_activity(p_user_id), 0));
$$;

create or replace function public.get_activity_heatmap(p_user_id uuid default null)
returns table(activity_date date, activity_count integer)
language sql stable security definer set search_path = public as $$
  with events as (
    select user_id, created_at from public.posts
    union all select user_id, created_at from public.moments
    union all select user_id, created_at from public.progress_logs
    union all select user_id, created_at from public.post_likes
    union all select user_id, created_at from public.content_likes
    union all select user_id, created_at from public.post_comments
    union all select user_id, created_at from public.content_comments
    union all select user_id, created_at from public.whispers
    union all select user_id, created_at from public.activity_checkins
  )
  select (created_at at time zone 'Asia/Shanghai')::date,
    count(*)::integer
  from events
  where (p_user_id is null or user_id = p_user_id)
    and created_at >= ((now() at time zone 'Asia/Shanghai')::date - 364)::timestamp
  group by 1 order by 1;
$$;

grant execute on function public.get_user_activity_summary(uuid) to anon, authenticated;
grant execute on function public.get_activity_heatmap(uuid) to anon, authenticated;

create or replace function public.get_public_whisper_summary(p_user_id uuid)
returns table(total_count bigint, previews jsonb)
language sql stable security definer set search_path = public as $$
  with recent as (
    select content, created_at from public.whispers
    where user_id = p_user_id and parent_id is null
    order by created_at desc limit 1
  ), totals as (
    select count(*)::bigint as total_count from public.whispers
    where user_id = p_user_id and parent_id is null
  )
  select totals.total_count,
    coalesce(jsonb_agg(jsonb_build_object('content', recent.content, 'created_at', recent.created_at)
      order by recent.created_at desc) filter (where recent.created_at is not null), '[]'::jsonb)
  from totals left join recent on true group by totals.total_count;
$$;
grant execute on function public.get_public_whisper_summary(uuid) to anon, authenticated;

-- Public mini-game guests and administrator-managed friend links.
create table if not exists public.jump_game_guest_scores (
  guest_token text primary key check (char_length(guest_token) between 20 and 100),
  display_name text not null unique,
  best_score integer not null default 0 check (best_score between 0 and 1000000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.jump_game_guest_scores enable row level security;
grant select on public.jump_game_guest_scores to anon, authenticated;
drop policy if exists "guest jump scores are readable" on public.jump_game_guest_scores;
create policy "guest jump scores are readable" on public.jump_game_guest_scores for select using (true);

create or replace function public.submit_guest_jump_game_score(p_guest_token text, p_score integer)
returns table(guest_token text, display_name text, best_score integer)
language plpgsql security definer set search_path = public as $$
declare next_name text;
begin
  if p_guest_token is null or char_length(p_guest_token) < 20 or char_length(p_guest_token) > 100 then raise exception '游客身份无效'; end if;
  if p_score is null or p_score < 0 or p_score > 1000000 then raise exception '无效的游戏分数'; end if;
  select g.display_name into next_name from public.jump_game_guest_scores g where g.guest_token = p_guest_token;
  if next_name is null then
    next_name := '罗星人' || ((select count(*) from public.jump_game_guest_scores) + 1)::text;
  end if;
  insert into public.jump_game_guest_scores (guest_token, display_name, best_score, updated_at)
  values (p_guest_token, next_name, p_score, now())
  on conflict on constraint jump_game_guest_scores_pkey do update set
    best_score = greatest(public.jump_game_guest_scores.best_score, excluded.best_score),
    updated_at = case when excluded.best_score > public.jump_game_guest_scores.best_score then now() else public.jump_game_guest_scores.updated_at end;
  return query select g.guest_token, g.display_name, g.best_score from public.jump_game_guest_scores g where g.guest_token = p_guest_token;
end;
$$;

create or replace function public.list_jump_game_leaderboard(p_limit integer default 20)
returns table(player_key text, display_name text, avatar_url text, best_score integer, is_guest boolean)
language sql stable security definer set search_path = public as $$
  select * from (
    select 'user:' || s.user_id::text as player_key,
      coalesce(nullif(p.display_name, ''), '普通用户') as display_name,
      p.avatar_url as avatar_url,
      s.best_score as best_score,
      false as is_guest
    from public.jump_game_scores s left join public.profiles p on p.id = s.user_id
    union all
    select 'guest:' || g.guest_token as player_key,
      g.display_name as display_name,
      null::text as avatar_url,
      g.best_score as best_score,
      true as is_guest
    from public.jump_game_guest_scores g
  ) ranked order by best_score desc, display_name asc limit greatest(1, least(coalesce(p_limit, 20), 100));
$$;
grant execute on function public.submit_guest_jump_game_score(text, integer) to anon, authenticated;
grant execute on function public.list_jump_game_leaderboard(integer) to anon, authenticated;

