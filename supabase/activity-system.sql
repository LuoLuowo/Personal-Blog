-- Ordinary users need 10 activity points to publish comments and whispers.
drop policy if exists "users add comments" on public.post_comments;
create policy "users add comments" on public.post_comments
  for insert to authenticated with check (auth.uid() = user_id and public.has_activity_access(10));

drop policy if exists "users add own content comments" on public.content_comments;
create policy "users add own content comments" on public.content_comments
  for insert to authenticated with check (auth.uid() = user_id and public.has_activity_access(10));

drop policy if exists "users publish own whispers" on public.whispers;
create policy "users publish own whispers" on public.whispers
  for insert to authenticated with check (auth.uid() = user_id and public.has_activity_access(10));

-- Daily heatmap, one-level whisper replies and administrator-managed inspiration templates.
alter table public.whispers add column if not exists parent_id uuid references public.whispers(id) on delete cascade;
create index if not exists whispers_parent_id_idx on public.whispers (parent_id);

create or replace function public.validate_whisper_reply_depth()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.parent_id is not null and exists (
    select 1 from public.whispers where id = new.parent_id and parent_id is not null
  ) then
    raise exception '碎碎念最多只能回复一层';
  end if;
  return new;
end;
$$;
drop trigger if exists validate_whisper_reply_depth_trigger on public.whispers;
create trigger validate_whisper_reply_depth_trigger before insert or update of parent_id on public.whispers
  for each row execute function public.validate_whisper_reply_depth();

