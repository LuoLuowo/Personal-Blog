create table if not exists public.activity_checkins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  checkin_date date not null default ((now() at time zone 'Asia/Shanghai')::date),
  created_at timestamptz not null default now(),
  unique (user_id, checkin_date)
);

alter table public.activity_checkins enable row level security;
grant select, insert on public.activity_checkins to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "users read own activity checkins" on public.activity_checkins;
drop policy if exists "users add own activity checkins" on public.activity_checkins;
create policy "users read own activity checkins" on public.activity_checkins
  for select to authenticated using (auth.uid() = user_id or public.is_blog_admin());
create policy "users add own activity checkins" on public.activity_checkins
  for insert to authenticated with check (auth.uid() = user_id);

create or replace function public.activity_title(p_score integer)
returns text
language sql
immutable
as $$
  select case
    when p_score >= 4000 then '罗客神'
    when p_score >= 2000 then '全站星使'
    when p_score >= 1000 then '罗客星使'
    when p_score >= 800 then '拾星罗客'
    when p_score >= 500 then '拾光罗客'
    when p_score >= 300 then '深知罗者'
    when p_score >= 200 then '熟知罗者'
    when p_score >= 100 then '知罗者'
    when p_score >= 50 then '漂泊者'
    else '初入人'
  end;
$$;

create or replace function public.calculate_user_activity(p_user_id uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select greatest(0,
    10
    + case when nullif(btrim(p.mbti), '') is not null then 20 else 0 end
    + case when nullif(btrim(p.gender), '') is not null then 10 else 0 end
    + case when jsonb_typeof(coalesce(p.personal_tags, '[]'::jsonb)) = 'array'
             and jsonb_array_length(coalesce(p.personal_tags, '[]'::jsonb)) > 0 then 20 else 0 end
    + 20 * (select count(*)::integer from public.activity_checkins c where c.user_id = p_user_id)
    + 5 * (select count(*)::integer from public.post_likes l where l.user_id = p_user_id)
    + 5 * (select count(*)::integer from public.content_likes l where l.user_id = p_user_id)
    + 5 * (select count(*)::integer from public.post_comments c where c.user_id = p_user_id)
    + 5 * (select count(*)::integer from public.content_comments c where c.user_id = p_user_id)
    + 5 * (select count(*)::integer from public.whispers w where w.user_id = p_user_id)
  )::integer
  from public.profiles p
  where p.id = p_user_id;
$$;

create or replace function public.has_activity_access(p_required integer)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_blog_admin() or coalesce(public.calculate_user_activity(auth.uid()), 0) >= p_required;
$$;

create or replace function public.get_my_activity_status()
returns table (
  score integer,
  title text,
  checked_today boolean,
  next_score integer,
  next_title text
)
language sql
stable
security definer
set search_path = public
as $$
  with current_score as (
    select coalesce(public.calculate_user_activity(auth.uid()), 0)::integer as value
  )
  select
    value,
    public.activity_title(value),
    exists(
      select 1 from public.activity_checkins
      where user_id = auth.uid()
        and checkin_date = (now() at time zone 'Asia/Shanghai')::date
    ),
    case
      when value < 50 then 50 when value < 100 then 100 when value < 200 then 200
      when value < 300 then 300 when value < 500 then 500 when value < 800 then 800
      when value < 1000 then 1000 when value < 2000 then 2000 when value < 4000 then 4000
      else value
    end,
    case
      when value < 50 then '漂泊者' when value < 100 then '知罗者' when value < 200 then '熟知罗者'
      when value < 300 then '深知罗者' when value < 500 then '拾光罗客' when value < 800 then '拾星罗客'
      when value < 1000 then '罗客星使' when value < 2000 then '全站星使' when value < 4000 then '罗客神'
      else '罗客神'
    end
  from current_score;
$$;

create or replace function public.daily_activity_checkin()
returns table (score integer, title text, checked_today boolean)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception '请先登录'; end if;
  insert into public.activity_checkins (user_id, checkin_date)
  values (auth.uid(), (now() at time zone 'Asia/Shanghai')::date)
  on conflict (user_id, checkin_date) do nothing;
  return query select public.calculate_user_activity(auth.uid()), public.activity_title(public.calculate_user_activity(auth.uid())), true;
end;
$$;

create or replace function public.list_activity_leaderboard()
returns table (
  user_id uuid,
  display_name text,
  avatar_url text,
  is_admin boolean,
  score integer,
  title text,
  rank bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with scores as (
    select p.id, coalesce(nullif(btrim(p.display_name), ''), '普通用户') as display_name,
      p.avatar_url, coalesce(p.is_admin, false) as is_admin,
      public.calculate_user_activity(p.id) as score
    from public.profiles p
  )
  select id, display_name, avatar_url, is_admin, score, public.activity_title(score),
    dense_rank() over (order by score desc, display_name asc)
  from scores
  order by score desc, display_name asc;
$$;

